# Sourced by the scripts that report or check whether a lane's work is pushed.
#
# "Unpushed" means: commits on HEAD that no origin/* branch has. It deliberately does not use the
# branch's configured upstream: `lane start` creates the lane branch from origin/<base>, so the
# upstream is origin/<base>, and a plain `git push origin <id>` (no -u) never changes that. Counting
# against it said "unpushed" after a push, and counted base-branch commits as pushed work before one.

# Claude Code names a project's folder after its absolute path with every character that is not a
# letter, digit or dash turned into "-" (so "." and spaces too, not just "/" and "_" as lib.sh's
# claude_project_dir has it). Redefined here so every script that sources this file gets the full rule.
claude_project_dir(){ printf '%s' "$1" | sed 's#[^A-Za-z0-9-]#-#g'; }

# lane_has_origin <worktree> : does this repo have an origin remote at all?
lane_has_origin(){ git -C "$1" remote get-url origin >/dev/null 2>&1; }

# lane_unpushed <worktree> : a number, "?" when git cannot say, "local" when there is no origin
lane_unpushed(){
  lane_has_origin "$1" || { echo local; return 0; }
  git -C "$1" rev-list --count HEAD --not --remotes=origin 2>/dev/null || echo '?'
}

# lane_secret_paths <root> [--skip-links] : reads NUL-separated paths (relative to <root>) on stdin,
# writes NUL-separated those whose NAME says secret. Same pattern as SECRET_FILE in
# hooks/guard.py (tests/t_secretnames.sh fails if they ever differ), and templates (.env.example, ...)
# are not secrets. --skip-links leaves out symlinks: `lane start` links env files in from the
# mirror, so deleting the link loses nothing.
lane_secret_paths(){
  python3 -c '
import os,re,sys
rx = re.compile(r"(^|/)(\.env(\.[\w.-]+)?|id_(rsa|ed25519|ecdsa|dsa)|\.netrc|\.npmrc|\.pgpass|\.git-credentials|\.htpasswd|[^/]*\.(pem|key|p12|pfx|p8|jks|keystore|kdbx)|[^/]*credentials[^/]*\.json|service-account[^/]*\.json|secrets?\.(json|ya?ml|toml))$", re.I | re.M)
safe = re.compile(r"\.(example|sample|template|dist)$", re.I | re.M)
root, skip = sys.argv[1], "--skip-links" in sys.argv[2:]
for p in sys.stdin.buffer.read().decode("utf-8", "surrogateescape").split("\0"):
    if not p or not rx.search(p.rstrip("/")) or safe.search(p.rstrip("/")): continue
    if skip and os.path.islink(os.path.join(root, p)): continue
    sys.stdout.buffer.write(p.encode("utf-8", "surrogateescape") + b"\0")' "$@"
}

# lane_unpushed_text <worktree> : "N unpushed", or the plain truth for a repo with no origin
lane_unpushed_text(){
  local n; n=$(lane_unpushed "$1")
  if [ "$n" = local ]; then echo "local-only (no origin)"; else echo "$n unpushed"; fi
}

# lane_drop_dep_paths : NUL-separated paths on stdin -> those NOT inside a dependency/build tree
# (node_modules, .venv, venv, vendor, target, dist, build, __pycache__, .nx, .git). Secret-NAMED
# files there are test fixtures and vendored keys, regenerated by an install or a build. The list
# starts from lane-env-check's prune list.
lane_drop_dep_paths(){
  python3 -c '
import sys
dep = {"node_modules", ".venv", "venv", "vendor", "target", "dist", "build", "__pycache__", ".nx", ".git", ".tox", ".mypy_cache", ".pytest_cache", ".gradle", ".next", ".cache"}
for p in sys.stdin.buffer.read().split(b"\0"):
    if not p or any(c.decode("utf-8", "surrogateescape") in dep for c in p.split(b"/")[:-1]): continue
    sys.stdout.buffer.write(p + b"\0")'
}

# lane_untracked_secrets <worktree> : the UNTRACKED (not ignored) files in it whose NAME says secret,
# space-separated. These are what `lane park` leaves out of its wip commit and leaves on disk.
lane_untracked_secrets(){ # [--skip-links] leaves out symlinks (env files `lane start` links in from the mirror)
  local out; out=$(git -C "$1" ls-files -o --exclude-standard -z 2>/dev/null | lane_secret_paths "$1" ${2:+"$2"} | tr '\0' ' ')
  printf '%s' "${out% }"
}

# lane_dirty_count <worktree> : changed entries (git status --porcelain lines) NOT counting untracked
# secret-named files. park deliberately leaves those out, so they are not unfinished work; the
# board, status and session-start must not call a freshly parked lane dirty because of them.
# A collapsed untracked directory counts as one entry unless every file in it is a secret.
lane_dirty_count(){
  local d="$1" secrets; secrets=$(git -C "$d" ls-files -o --exclude-standard -z 2>/dev/null | lane_secret_paths "$d" | tr '\0' '\n')
  git -C "$d" status --porcelain -z 2>/dev/null | LANE_SECRETS="$secrets" python3 -c '
import os, subprocess, sys
sec = set(x for x in os.environ.get("LANE_SECRETS", "").split("\n") if x)
f = sys.stdin.buffer.read().split(b"\0"); i = 0; n = 0; untracked = None
while i < len(f):
    e = f[i].decode("utf-8", "surrogateescape"); i += 1
    if len(e) < 4: continue
    if e[0] in "RC" or e[1] in "RC": i += 1
    if e[:2] != "??": n += 1; continue
    p = e[3:]
    if not p.endswith("/"): n += 0 if p in sec else 1; continue
    if untracked is None:
        untracked = subprocess.run(["git", "-C", sys.argv[1], "ls-files", "-o", "--exclude-standard", "-z"], capture_output=True).stdout.decode("utf-8", "surrogateescape").split("\0")
    if any(u.startswith(p) and u not in sec for u in untracked): n += 1
print(n)' "$d"
}
